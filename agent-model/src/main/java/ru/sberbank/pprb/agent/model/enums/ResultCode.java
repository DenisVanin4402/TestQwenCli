package ru.sberbank.pprb.agent.model.enums;

/**
 * Закрытый набор причин ответа приложения. Тип защищает внутренний контракт между хранением,
 * оркестратором и адаптерами; строковое имя появляется только при построении внешнего ответа.
 */
public enum ResultCode {
    /** Текущий шаг предлагает выбрать операцию. */
    OPERATION_CHOICE_REQUIRED,
    /** Кнопка, управляющее действие или текст поступили одновременно. */
    INPUT_SOURCE_CONFLICT,
    /** Несколько действий либо действие вместе со справочным вопросом. */
    MULTIPLE_ACTIONS,
    /** Справка по переданным знаниям. */
    REFERENCE_ANSWER,
    /** В знаниях нет сведений по вопросу. */
    REFERENCE_NOT_FOUND,
    /** Справочный вызов завершился техническим сбоем. */
    REFERENCE_FAILED,
    /** Команда не распознана; требуется повторная формулировка без изменения сессии. */
    CLARIFICATION_REQUIRED,
    /** Текст не удалось обработать технически; событие не исполнялось. */
    TEXT_ANALYSIS_FAILED,
    /** Подготовка ожидает отдельного согласия. */
    CONFIRMATION_REQUIRED,
    /** Пользователь отменил подготовку. */
    PREPARATION_CANCELLED,
    /** Для отмены нет активной подготовки. */
    NO_ACTIVE_PREPARATION,
    /** Менеджер принял подтверждённую операцию без ошибки. */
    REQUEST_SUBMITTED,
    /** Завершённая сессия не принимает новые операции. */
    SESSION_COMPLETED,
    /** Команда недопустима на текущем шаге. */
    INVALID_COMMAND,
    /** Входные данные неполны или имеют неверную форму. */
    INVALID_REQUEST,
    /** Состав или формат подтверждения некорректен. */
    INVALID_CONFIRMATION,
    /** Согласие относится к другой подготовке. */
    STALE_PREPARATION,
    /** Подтверждённые значения не совпали со снимком. */
    CONFIRMATION_MISMATCH,
    /** Команда отсутствует в поддерживаемом профиле. */
    UNSUPPORTED_COMMAND,
    /** Переданный контекст противоречит сохранённому платежу. */
    CONTEXT_MISMATCH,
    /** Семафор сессии занят другим сообщением. */
    SESSION_BUSY,
    /** Запрошенная сессия отсутствует. */
    SESSION_NOT_FOUND,
    /** Действие не завершилось успешно; внешний эффект мог состояться. */
    OPERATION_FAILED,
    /** Состояние сессии нельзя достоверно прочитать или сохранить. */
    STORAGE_UNAVAILABLE
}
