package ru.sberbank.pprb.agent.model.enums;

/**
 * События, в которые преобразуются команды пользователя перед передачей в машину состояний.
 * Допустимость события на текущем шаге и конкретный переход определяет сама машина.
 */
public enum SessionEvent {
    /** Пользователь выбирает запрос статуса; переход допустим только на шаге выбора операции. */
    SELECT,
    /**
     * Пользователь отдельным сообщением подтверждает данные текущего черновика и разрешает
     * отправку.
     */
    CONFIRM,
    /** Пользователь отказывается от текущего черновика; при наличии подготовки она отменяется. */
    CANCEL
}
